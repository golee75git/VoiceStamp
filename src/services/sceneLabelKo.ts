export function translateSceneLabel(text: string): string {
  const trimmed = text.trim();
  if (!trimmed) {
    return trimmed;
  }
  const direct = SCENE_LABEL_KO[trimmed.toLowerCase()];
  if (direct) {
    return direct;
  }
  return trimmed;
}
